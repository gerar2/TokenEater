import Testing
import Foundation

@Suite("TerminalIntegrationGenerator")
struct TerminalIntegrationGeneratorTests {

    private static func entry(
        _ name: String,
        profileName: String,
        accountUUID: String? = "acc-\(UUID().uuidString)",
        color: WarpTabColor = .blue,
        id: UUID = UUID()
    ) -> TerminalAccountEntry {
        TerminalAccountEntry(
            name: name,
            profileID: id,
            profileName: profileName,
            accountUUID: accountUUID,
            warpColor: color,
            keychainService: TerminalTokenKeychain.service(for: id)
        )
    }

    /// Profile names are free text: every character that means something to
    /// zsh or TOML.
    private static let nastyProfileName = #"O'Brien "quoted" $HOME `touch pwned` $(id) \back\slash; *"#

    /// `zsh -n` (parse only, nothing runs) on `script`.
    private func zshSyntaxCheck(_ script: String) throws -> (status: Int32, stderr: String) {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("te-gen-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let file = dir.appendingPathComponent("claude-accounts.zsh")
        try Data(script.utf8).write(to: file)

        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/zsh")
        process.arguments = ["-f", "-n", file.path]
        process.environment = ["PATH": "/usr/bin:/bin", "HOME": dir.path]
        let stderr = Pipe()
        process.standardError = stderr
        process.standardOutput = FileHandle.nullDevice
        process.standardInput = FileHandle.nullDevice
        try process.run()
        let errorText = String(decoding: stderr.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        process.waitUntilExit()
        return (process.terminationStatus, errorText)
    }

    // MARK: - Tab Config

    @Test("The Tab Config stem is tokeneater_<name>")
    func stem() {
        #expect(TerminalIntegrationGenerator.tabConfigStem(for: "gpt") == "tokeneater_gpt")
        #expect(TerminalIntegrationGenerator.tabConfigStem(for: "4gentic-dev") == "tokeneater_4gentic-dev")
    }

    @Test("The Tab Config names, titles and colours the tab, and runs cla with the handoff flag")
    func tabConfigContent() {
        let config = TerminalIntegrationGenerator.warpTabConfig(for: Self.entry("4gentic", profileName: "4gentic Dev", color: .green))
        #expect(config == """
        # Generated by TokenEater - overwritten whenever your accounts change.
        name = "Claude · 4gentic Dev"
        title = "claude · 4gentic"
        color = "green"

        [[panes]]
        id = "main"
        type = "terminal"
        commands = ["cla 4gentic --te-pending"]

        """)
    }

    @Test("Every Warp colour is written as its lowercase name", arguments: WarpTabColor.allCases)
    func tabConfigColour(color: WarpTabColor) {
        let config = TerminalIntegrationGenerator.warpTabConfig(for: Self.entry("a", profileName: "A", color: color))
        #expect(config.contains("\ncolor = \"\(color.rawValue)\"\n"))
    }

    @Test("TOML strings escape backslashes, quotes and control characters from the profile name")
    func tomlEscaping() {
        let config = TerminalIntegrationGenerator.warpTabConfig(
            for: Self.entry("gpt", profileName: "Say \"hi\" \\ there\tnow\nnext\u{1}")
        )
        #expect(config.contains(#"name = "Claude · Say \"hi\" \\ there\tnow\nnext\u0001""# + "\n"))
        // The free text never adds lines or keys to the document.
        #expect(config.components(separatedBy: "\n").count == 10)
    }

    @Test("A command name that is not a plain word is shell-quoted inside the Tab Config")
    func tabConfigQuotesOddNames() {
        let config = TerminalIntegrationGenerator.warpTabConfig(for: Self.entry("a b'c", profileName: "X"))
        #expect(config.contains(#"commands = ["cla 'a b'\\''c' --te-pending"]"#))
    }

    @Test("Generated files carry the marker on their first line")
    func markerOnFirstLine() {
        let entry = Self.entry("gpt", profileName: "GPT")
        for text in [TerminalIntegrationGenerator.warpTabConfig(for: entry), TerminalIntegrationGenerator.zshScript(for: [entry])] {
            let first = text.components(separatedBy: "\n")[0]
            #expect(first.hasPrefix("# "))
            #expect(first.contains(TerminalIntegrationGenerator.marker))
        }
    }

    // MARK: - zsh script

    @Test("The script lists every account in the three tables, single-quoted")
    func scriptTables() {
        let id = UUID(uuidString: "11111111-2222-3333-4444-555555555555")!
        let withAccount = Self.entry("4gentic", profileName: "4gentic Dev", accountUUID: "acc-1", id: id)
        let withoutAccount = Self.entry("gpt", profileName: "GPT", accountUUID: nil)
        let script = TerminalIntegrationGenerator.zshScript(for: [withAccount, withoutAccount])

        #expect(script.contains("typeset -gA _te_service _te_account _te_label\n"))
        #expect(script.contains("""
        _te_service=(
          '4gentic' 'TokenEater terminal token: 11111111-2222-3333-4444-555555555555'
          'gpt' '\(withoutAccount.keychainService)'
        )
        _te_account=(
          '4gentic' 'acc-1'
          'gpt' ''
        )
        _te_label=(
          '4gentic' '4gentic Dev'
          'gpt' 'GPT'
        )
        """))
        #expect(script.contains("function cla {"))
        #expect(script.contains("function claw {"))
        #expect(script.contains("zmodload zsh/datetime"))
    }

    @Test("Names full of shell syntax are single-quoted with ' written as '\\''")
    func scriptQuotesNastyNames() {
        let entry = Self.entry(#"we'ird"$`x`"#, profileName: Self.nastyProfileName)
        let script = TerminalIntegrationGenerator.zshScript(for: [entry])

        #expect(script.contains(#"  'we'\''ird"$`x`' '\#(entry.keychainService)'"#))
        #expect(script.contains(#"  'we'\''ird"$`x`' 'O'\''Brien "quoted" $HOME `touch pwned` $(id) \back\slash; *'"#))
    }

    @Test("An empty catalog still yields empty tables and the functions")
    func emptyCatalog() {
        let script = TerminalIntegrationGenerator.zshScript(for: [])
        #expect(script.contains("_te_service=()\n_te_account=()\n_te_label=()\n"))
        #expect(script.contains("function cla {"))
    }

    @Test("shellQuoted wraps in single quotes and survives every special character")
    func shellQuoting() {
        #expect(TerminalIntegrationGenerator.shellQuoted("plain") == "'plain'")
        #expect(TerminalIntegrationGenerator.shellQuoted("") == "''")
        #expect(TerminalIntegrationGenerator.shellQuoted("it's") == #"'it'\''s'"#)
        #expect(TerminalIntegrationGenerator.shellQuoted(#"$x "y" `z` \"#) == #"'$x "y" `z` \'"#)
        #expect(TerminalIntegrationGenerator.shellQuoted("a\0b") == "'ab'")
        #expect(TerminalIntegrationGenerator.shellWord("gpt-2") == "gpt-2")
        #expect(TerminalIntegrationGenerator.shellWord("a b") == "'a b'")
        #expect(TerminalIntegrationGenerator.shellWord("") == "''")
    }

    @Test("zsh -n accepts the generated script", arguments: [0, 1, 3])
    func zshParsesScript(accounts: Int) throws {
        let entries = (0..<accounts).map { index in
            Self.entry(
                index == 2 ? #"we'ird"$`x`"# : "account-\(index)",
                profileName: index == 0 ? "Plain" : Self.nastyProfileName,
                accountUUID: index == 1 ? nil : "acc-\(index)"
            )
        }
        let result = try zshSyntaxCheck(TerminalIntegrationGenerator.zshScript(for: entries))
        #expect(result.status == 0)
        #expect(result.stderr.isEmpty)
    }

    @Test("The syntax check itself rejects a broken script")
    func zshSyntaxCheckCatchesErrors() throws {
        let broken = TerminalIntegrationGenerator.zshScript(for: []) + "\nfunction broken {\n  if true; then\n}\n"
        #expect(try zshSyntaxCheck(broken).status != 0)
    }
}
