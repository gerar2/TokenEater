import Foundation

/// Builds the files of the terminal integration (`docs/terminal-accounts-plan.md`
/// §3.2): the zsh script with the `cla` / `claw` functions and one Warp Tab
/// Config per account. Pure text generation; `TerminalIntegrationService`
/// writes the results to disk.
///
/// Every value that comes from the catalog is quoted for its destination
/// (single quotes for zsh, basic strings for TOML), so a profile name full of
/// quotes, `$` or backticks can never break the script or run anything.
enum TerminalIntegrationGenerator {
    /// First-line marker of every generated file. The service only prunes Tab
    /// Configs carrying it, so files a user made by hand are never touched.
    static let marker = "Generated by TokenEater"

    /// First line of every generated file.
    static let headerLine = "# \(marker) - overwritten whenever your accounts change."

    static let tabConfigPrefix = "tokeneater_"

    /// Flag the Warp tab passes to `cla` so it picks up the `claw` handoff.
    static let pendingFlag = "--te-pending"

    /// File stem of an account's Tab Config, also its `warp://tab_config/<stem>` name.
    static func tabConfigStem(for name: String) -> String {
        tabConfigPrefix + name
    }

    // MARK: - Warp Tab Config

    /// The Tab Config Warp opens for `claw <name>`: a tab titled and coloured
    /// for the account whose only command consumes the pending handoff.
    static func warpTabConfig(for entry: TerminalAccountEntry) -> String {
        let command = "cla \(shellWord(entry.name)) \(pendingFlag)"
        return """
        \(headerLine)
        name = \(tomlString("Claude · " + entry.profileName))
        title = \(tomlString("claude · " + entry.name))
        color = \(tomlString(entry.warpColor.rawValue))

        [[panes]]
        id = "main"
        type = "terminal"
        commands = [\(tomlString(command))]

        """
    }

    // MARK: - zsh script

    /// `~/.config/tokeneater/claude-accounts.zsh`: the account tables followed
    /// by the functions. The tables are plain data so the functions never
    /// depend on how many accounts exist or what they are called.
    static func zshScript(for entries: [TerminalAccountEntry]) -> String {
        var script = """
        \(headerLine)
        #
        # Terminal accounts (TokenEater -> Settings -> Accounts -> Terminal):
        #   cla <account> [claude args...]              Claude Code here, with that account
        #   claw [-w|--new-window] <account> [args...]  new Warp tab (or window) for it, same directory
        #   cla                                         list the accounts
        # Every account shares ~/.claude; only the credential changes.
        # Overrides (tests, unusual setups): TOKENEATER_SECURITY_BIN, TOKENEATER_PLUTIL_BIN,
        # TOKENEATER_CLAUDE_BIN, TOKENEATER_OPEN_BIN, TOKENEATER_PENDING_DIR.

        zmodload zsh/datetime 2>/dev/null

        typeset -gA _te_service _te_account _te_label

        """
        script += table("_te_service", entries.map { ($0.name, $0.keychainService) })
        script += table("_te_account", entries.map { ($0.name, $0.accountUUID ?? "") })
        script += table("_te_label", entries.map { ($0.name, $0.profileName) })
        script += "\n" + functions
        return script
    }

    /// `name=( 'key' 'value' … )`: an associative array filled in one
    /// assignment, which also clears entries left over from a previous version
    /// of the script when the shell sources it again.
    private static func table(_ name: String, _ pairs: [(String, String)]) -> String {
        guard !pairs.isEmpty else { return "\(name)=()\n" }
        let rows = pairs.map { "  \(shellQuoted($0.0)) \(shellQuoted($0.1))" }
        return "\(name)=(\n" + rows.joined(separator: "\n") + "\n)\n"
    }

    /// The functions are the same for every catalog. Design notes:
    /// - `function name { }` rather than `name() { }`: a user alias called
    ///   `cla` would otherwise be expanded while the definition is parsed.
    /// - `emulate -L zsh` shields the bodies from the user's options
    ///   (`ksh_arrays`, `sh_word_split`, `no_unset`, `err_return`…) and
    ///   restores them on return; `builtin cd` / `command rm` dodge aliases.
    /// - The token only exists in a `local` and in the environment of the one
    ///   `claude` process (`VAR=value command claude`), never in the shell.
    /// - The `claw` handoff holds the directory and arguments quoted with
    ///   `(q)`, which keeps any character (newlines included) on one line;
    ///   `cla --te-pending` reads it back with `eval "stored=( … )"` only when
    ///   the file is owned by the user and at most 120 s old, and deletes it
    ///   in every case.
    private static let functions = #"""
    # Help text: every account with its profile name and how `cla` signs it in.
    function _te_usage {
      emulate -L zsh
      print -r -- 'Usage: cla <account> [claude args...]'
      print -r -- '       claw [-w|--new-window] <account> [claude args...]'
      print -r -- ''
      if (( ${#_te_service} == 0 )); then
        print -r -- 'No accounts yet: add one in TokenEater -> Settings -> Accounts.'
        return 0
      fi
      print -r -- 'Accounts:'
      local live=$(_te_live_account) name state
      local -i width=0
      for name in ${(k)_te_service}; do
        (( ${#name} > width )) && width=${#name}
      done
      for name in ${(ko)_te_service}; do
        if _te_has_token $name; then
          state='terminal token'
        elif [[ -n ${_te_account[$name]} && ${_te_account[$name]} == "$live" ]]; then
          state='session of ~/.claude'
        else
          state='no token'
        fi
        print -r -- "  ${(r:width:)name}  ${_te_label[$name]}  ($state)"
      done
    }

    # Account signed in to Claude Code's global config (empty when unknown).
    function _te_live_account {
      emulate -L zsh
      local config=${CLAUDE_CONFIG_DIR:+$CLAUDE_CONFIG_DIR/.claude.json}
      config=${config:-$HOME/.claude.json}
      [[ -f $config ]] || return 0
      "${TOKENEATER_PLUTIL_BIN:-/usr/bin/plutil}" -extract oauthAccount.accountUuid raw -o - "$config" 2>/dev/null
    }

    # Whether the Keychain holds the account's terminal token (attributes only).
    function _te_has_token {
      emulate -L zsh
      "${TOKENEATER_SECURITY_BIN:-/usr/bin/security}" find-generic-password \
        -a "${USER:-$USERNAME}" -s "${_te_service[$1]}" >/dev/null 2>&1
    }

    function cla {
      emulate -L zsh
      if (( $# == 0 )) || [[ $1 == (-h|--help) ]]; then
        _te_usage
        return 0
      fi
      local name=$1
      shift
      if (( ! ${+_te_service[$name]} )); then
        print -ru2 -- "cla: unknown account '$name'"
        _te_usage >&2
        return 2
      fi

      # Started by a `claw` Warp tab: go back to the directory `claw` ran in
      # and put its arguments first. No usable handoff: the home directory.
      if [[ ${1:-} == --te-pending ]]; then
        shift
        local pending=${TOKENEATER_PENDING_DIR:-$HOME/.config/tokeneater/pending}/$name
        local stamp= dir= line= target=$HOME
        local -a stored
        if [[ -f $pending && -O $pending ]]; then
          { IFS= read -r stamp; IFS= read -r dir; IFS= read -r line; } < $pending
          local -i now=${EPOCHSECONDS:-$(command date +%s)}
          if [[ $stamp == <-> ]] && (( now - stamp >= 0 && now - stamp <= 120 )); then
            target=${(Q)dir}
            eval "stored=( $line )"
          fi
        fi
        command rm -f -- $pending 2>/dev/null
        builtin cd -- $target || print -ru2 -- "cla: staying in $PWD"
        set -- "${stored[@]}" "$@"
      fi

      local claude=${TOKENEATER_CLAUDE_BIN:-claude} token
      token=$("${TOKENEATER_SECURITY_BIN:-/usr/bin/security}" find-generic-password \
        -a "${USER:-$USERNAME}" -s "${_te_service[$name]}" -w 2>/dev/null)
      if [[ -n $token ]]; then
        [[ -t 1 ]] && print -rn -- $'\e]0;'"claude · $name"$'\a'
        CLAUDE_CODE_OAUTH_TOKEN=$token command "$claude" "$@"
        return
      fi

      # No terminal token: fine when this account is the one signed in to
      # ~/.claude, which plain `claude` already uses.
      local expected=${_te_account[$name]}
      if [[ -n $expected && $(_te_live_account) == "$expected" ]]; then
        [[ -t 1 ]] && print -rn -- $'\e]0;'"claude · $name"$'\a'
        if (( ${+CLAUDE_CODE_OAUTH_TOKEN} )); then
          # A token exported in this shell would win over the ~/.claude session.
          ( unset CLAUDE_CODE_OAUTH_TOKEN; command "$claude" "$@" )
        else
          command "$claude" "$@"
        fi
        return
      fi
      print -ru2 -- "cla: No terminal token for $name - TokenEater → Settings → Accounts → ${_te_label[$name]} → Terminal"
      return 1
    }

    function claw {
      emulate -L zsh
      local query=
      if [[ ${1:-} == (-w|--new-window) ]]; then
        query='?new_window=true'
        shift
      fi
      if (( $# == 0 )) || [[ $1 == (-h|--help) ]]; then
        _te_usage
        return 0
      fi
      local name=$1
      shift
      if (( ! ${+_te_service[$name]} )); then
        print -ru2 -- "claw: unknown account '$name'"
        _te_usage >&2
        return 2
      fi
      # Handoff for the new tab: time, directory, arguments. Never the token.
      # umask 077 in a subshell: 0700 directory, 0600 file, shell untouched.
      local dir=${TOKENEATER_PENDING_DIR:-$HOME/.config/tokeneater/pending}
      if ! ( umask 077
             command mkdir -p -- $dir &&
             print -rl -- "${EPOCHSECONDS:-$(command date +%s)}" "${(q)PWD}" "${(j: :)${(q)@}}" >| $dir/$name ); then
        print -ru2 -- "claw: cannot write $dir/$name"
        return 1
      fi
      if ! "${TOKENEATER_OPEN_BIN:-/usr/bin/open}" "warp://tab_config/tokeneater_${name}${query}"; then
        command rm -f -- $dir/$name
        return 1
      fi
    }

    # Completion: account names first, then whatever completes `claude` itself.
    function _te_cla {
      local -i first=2
      if [[ $words[1] == claw && $words[2] == (-w|--new-window) ]]; then
        first=3
      fi
      if (( CURRENT == first )); then
        [[ $words[1] == claw ]] && (( first == 2 )) && compadd -- -w --new-window
        compadd -- ${(ko)_te_service}
      elif (( CURRENT > first )); then
        words=( claude "${(@)words[first+1,-1]}" )
        (( CURRENT -= first - 1 ))
        _normal
      fi
    }
    if (( ${+functions[compdef]} )); then
      compdef _te_cla cla claw
    fi

    """#

    // MARK: - Quoting

    /// A zsh single-quoted word: `'` becomes `'\''`. NUL is dropped (no shell
    /// string can hold it).
    static func shellQuoted(_ value: String) -> String {
        let cleaned = value.replacingOccurrences(of: "\0", with: "")
        return "'" + cleaned.replacingOccurrences(of: "'", with: #"'\''"#) + "'"
    }

    /// `value` as is when it is a plain word (always the case for a valid
    /// terminal name), quoted otherwise.
    static func shellWord(_ value: String) -> String {
        let plain = !value.isEmpty && value.unicodeScalars.allSatisfy {
            ("a"..."z").contains($0) || ("A"..."Z").contains($0) || ("0"..."9").contains($0)
                || $0 == "-" || $0 == "_" || $0 == "."
        }
        return plain ? value : shellQuoted(value)
    }

    /// A TOML basic string: `\` and `"` escaped, plus the control characters
    /// TOML forbids inside one (the profile name is free text).
    static func tomlString(_ value: String) -> String {
        var out = "\""
        for scalar in value.unicodeScalars {
            switch scalar {
            case "\\": out += "\\\\"
            case "\"": out += "\\\""
            case "\n": out += "\\n"
            case "\r": out += "\\r"
            case "\t": out += "\\t"
            case "\u{08}": out += "\\b"
            case "\u{0C}": out += "\\f"
            case _ where scalar.value < 0x20 || scalar.value == 0x7F:
                out += String(format: "\\u%04X", scalar.value)
            default: out.unicodeScalars.append(scalar)
            }
        }
        return out + "\""
    }
}
